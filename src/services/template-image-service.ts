import { randomBytes } from "node:crypto";
import { mkdir, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { prisma } from "@/db/client";
import { getAppUrl } from "@/lib/email-sending-config";
import {
  MAX_TEMPLATE_IMAGE_BYTES,
  TEMPLATE_IMAGE_SIZE_ERROR,
  TEMPLATE_IMAGE_TYPE_ERROR,
  TEMPLATE_IMAGE_TYPES,
  detectTemplateImageType,
} from "@/lib/template-images";

const DEFAULT_UPLOAD_DIR = "./uploads";
// The `turbopackIgnore` hints below stop the build from tracing (and bundling)
// the whole project because of these runtime-only upload paths.
// Public URL path the web server (nginx) maps onto UPLOAD_DIR.
const PUBLIC_UPLOAD_PATH = "/uploads";
const MAX_LISTED_IMAGES = 200;
// Organization ids are cuids; refuse anything that could escape UPLOAD_DIR.
const SAFE_PATH_SEGMENT = /^[A-Za-z0-9_-]+$/;

export class TemplateImageValidationError extends Error {}

export class TemplateImageNotFoundError extends Error {
  constructor() {
    super("Image not found.");
  }
}

export type TemplateImageSummary = {
  id: string;
  url: string;
  size: number;
  createdAt: Date;
};

const SUMMARY_SELECT = { id: true, url: true, size: true, createdAt: true } as const;

export function getUploadRoot(): string {
  return path.resolve(/*turbopackIgnore: true*/ process.env.UPLOAD_DIR?.trim() || DEFAULT_UPLOAD_DIR);
}

function organizationDir(organizationId: string): string {
  if (!SAFE_PATH_SEGMENT.test(organizationId)) {
    throw new Error("Invalid organization id for upload path.");
  }
  return path.join(/*turbopackIgnore: true*/ getUploadRoot(), organizationId);
}

export async function uploadTemplateImage(
  organizationId: string,
  bytes: Uint8Array
): Promise<TemplateImageSummary> {
  if (bytes.byteLength > MAX_TEMPLATE_IMAGE_BYTES) {
    throw new TemplateImageValidationError(TEMPLATE_IMAGE_SIZE_ERROR);
  }
  const mimeType = detectTemplateImageType(bytes);
  if (!mimeType) {
    throw new TemplateImageValidationError(TEMPLATE_IMAGE_TYPE_ERROR);
  }

  const dir = organizationDir(organizationId);
  const filename = `${randomBytes(16).toString("hex")}.${TEMPLATE_IMAGE_TYPES[mimeType]}`;
  const filePath = path.join(/*turbopackIgnore: true*/ dir, filename);

  await mkdir(dir, { recursive: true });
  // "wx" never overwrites an existing file.
  await writeFile(filePath, bytes, { flag: "wx" });

  try {
    return await prisma.templateImage.create({
      data: {
        organizationId,
        filename,
        url: `${getAppUrl()}${PUBLIC_UPLOAD_PATH}/${organizationId}/${filename}`,
        size: bytes.byteLength,
      },
      select: SUMMARY_SELECT,
    });
  } catch (error) {
    // Don't leave an orphaned file behind when the DB write fails.
    await unlink(filePath).catch(() => {});
    throw error;
  }
}

export async function listTemplateImages(organizationId: string): Promise<TemplateImageSummary[]> {
  return prisma.templateImage.findMany({
    where: { organizationId },
    orderBy: { createdAt: "desc" },
    take: MAX_LISTED_IMAGES,
    select: SUMMARY_SELECT,
  });
}

export async function deleteTemplateImage(organizationId: string, id: string): Promise<void> {
  const image = await prisma.templateImage.findFirst({
    where: { id, organizationId },
    select: { filename: true },
  });
  if (!image) throw new TemplateImageNotFoundError();

  const { count } = await prisma.templateImage.deleteMany({ where: { id, organizationId } });
  if (count === 0) throw new TemplateImageNotFoundError();

  // The stored filename was generated by us, but never trust it as a path.
  const filePath = path.join(/*turbopackIgnore: true*/ organizationDir(organizationId), path.basename(image.filename));
  try {
    await unlink(filePath);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") {
      console.error("Template image row deleted but file could not be removed:", filePath, error);
    }
  }
}
